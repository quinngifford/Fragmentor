import path from "node:path";
import type { Port } from "../model/block.js";
import { CAPABILITIES } from "../model/capabilities.js";
import type { CapabilityOperation } from "../model/capabilities.js";
import { describeType } from "../model/types.js";
import type { PortType } from "../model/types.js";
import { camelCase, pascalCase } from "./naming.js";
import { registerPack } from "./pack.js";
import type { ContractRequest, LanguagePack } from "./pack.js";
import { typescriptReach } from "./typescriptReach.js";

/**
 * TypeScript, as type declarations and nothing else.
 *
 * Fragmentor's own port notation is already TypeScript-shaped, so this pack
 * renders types by writing the notation out unchanged. That is a convenience
 * of this pack and not a fact about the model: every other pack translates.
 *
 * A contract is a declaration file holding types and no values. Code imports
 * it with `import type`, so it needs no package, and the compiler never writes
 * a declaration file out, so a codebase that compiles every `.ts` file it
 * finds builds exactly as it did before there were contracts in it. What a run
 * is given and gives back is checked against block.json itself, so Fragmentor
 * has no use for a schema here either.
 */

/**
 * A port's description, as the comment an editor shows beside it. A `*` then
 * `/` in it would end the comment early and break the file, so a backslash is
 * put between them.
 */
function commented(description: string | undefined): string {
  return description ? `  /** ${description.replaceAll("*/", "*\\/")} */\n` : "";
}

/** A block's ports as the object its code is handed, or hands back. */
function portsType(ports: Record<string, Port>): string {
  const entries = Object.entries(ports);
  if (entries.length === 0) return "{}";
  const lines = entries.map(([name, port]) => `${commented(port.description)}  ${name}: ${describeType(port.type)};`);
  return `{\n${lines.join("\n")}\n}`;
}

function relativeRootPrefix(blockPath: string): string {
  return "../".repeat(blockPath.split("/").length);
}

/**
 * How a capability port is written where a block declares it: `FileSystem`,
 * or `Store<Account>` for one that is a way into something with a shape.
 *
 * A bound port with nothing to fill in falls back to `unknown`, which is
 * honest — `check` reports the unbound port separately, and a contract that
 * would not compile helps nobody find it.
 */
function capabilityType(capability: string, row: PortType | undefined): string {
  const parameter = CAPABILITIES[capability]?.parameter;
  if (!parameter) return capability;
  return `${capability}<${row ? describeType(row) : "unknown"}>`;
}

function operationSignature(operation: CapabilityOperation): string {
  const parameters = operation.parameters.map((p) => `${p.name}: ${describeType(p.type)}`).join(", ");
  const returns = operation.returns ? describeType(operation.returns) : "void";
  return `  ${operation.name}(${parameters}): ${operation.async ? `Promise<${returns}>` : returns};`;
}

/** The path one project file writes to reach another, as an import: `../../blocks/app/log-in/contract.d.ts`. */
function relativeFrom(fromFile: string, toFile: string): string {
  const relative = path.posix.relative(path.posix.dirname(fromFile), toFile);
  return relative.startsWith(".") ? relative : `./${relative}`;
}

export const typescriptPack: LanguagePack = {
  id: "typescript",
  displayName: "TypeScript",
  contractPath: (blockPath) => `blocks/${blockPath}/contract.d.ts`,
  capabilitiesFile: "capabilities.d.ts",

  functionName: (blockId) => camelCase(blockId),
  typeName: (blockId, role) => `${pascalCase(blockId)}${role}`,
  typeExpression: (type) => describeType(type),

  contractSource({ block, blockPath, bound }: ContractRequest): string {
    const capabilities = Object.entries(block.capabilities);
    const capabilityTypes = [...new Set(capabilities.map(([, cap]) => cap.capability))].sort();

    const parts: string[] = [
      `// Generated by Fragmentor from block.json. Do not edit.`,
      `// ${block.name}: ${block.responsibility}`,
      ``,
    ];

    if (capabilityTypes.length > 0) {
      parts.push(`import type { ${capabilityTypes.join(", ")} } from "${relativeRootPrefix(blockPath)}capabilities.js";`, ``);
    }

    parts.push(
      `export type ${this.typeName(block.id, "Input")} = ${portsType(block.inputs)};`,
      ``,
      // Nothing to return is `void`, so the block's code returns nothing
      // rather than an empty object nobody asked for.
      `export type ${this.typeName(block.id, "Output")} = ${Object.keys(block.outputs).length === 0 ? "void" : portsType(block.outputs)};`,
      ``,
    );

    const capsName = this.typeName(block.id, "Caps");
    if (capabilities.length === 0) {
      // An empty interface, not `Record<string, never>`: a block that needs no
      // effects still has to accept whatever its caller passes on, and
      // `never` members would reject exactly that.
      parts.push(`/** ${block.name} needs no effects supplied from outside. */`);
      parts.push(`export interface ${capsName} {}`);
    } else {
      const fields = capabilities.map(
        ([name, cap]) => `${commented(cap.description)}  ${name}: ${capabilityType(cap.capability, bound?.[name])};`,
      );
      parts.push(`export interface ${capsName} {\n${fields.join("\n")}\n}`);
    }

    return `${parts.join("\n")}\n`;
  },

  capabilitiesSource(): string {
    const declarations = Object.values(CAPABILITIES).map((capability) => {
      const operations = capability.operations
        .map((operation) => `  /** ${operation.description} */\n${operationSignature(operation)}`)
        .join("\n");
      const head = capability.parameter ? `${capability.name}<${capability.parameter}>` : capability.name;
      return `/** ${capability.description} */\nexport interface ${head} {\n${operations}\n}`;
    });

    return `// Generated by Fragmentor. Do not edit.\n\n${declarations.join("\n\n")}\n`;
  },

  // What is compiled and run is JavaScript, so that is what an import names:
  // `contract.js` for `contract.d.ts`, which is where TypeScript looks for it.
  contractSpecifier: (contractPath, fromFile) => relativeFrom(fromFile, contractPath).replace(/([.]d)?[.]ts$/, ".js"),

  canRun: true,
  canCheck: true,
  reach: typescriptReach,
};

registerPack(typescriptPack);
