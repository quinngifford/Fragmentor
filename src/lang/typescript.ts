/**
 * TypeScript, validated with zod.
 *
 * Fragmentor's own port notation is already TypeScript-shaped, so this pack
 * renders types by writing the notation out unchanged. That is a convenience
 * of this pack and not a fact about the model: every other pack translates.
 */

const UNIMPLEMENTED = "has no implementation yet";

export function zodExpression(type: PortType): string {
  switch (type.kind) {
    case "string":
      return "z.string()";
    case "number":
      return "z.number()";
    case "boolean":
      return "z.boolean()";
    case "null":
      return "z.null()";
    case "unknown":
    case "text":
      return "z.unknown()";
    case "literal":
      return `z.literal(${JSON.stringify(type.value)})`;
    case "enum":
      return `z.enum([${type.values.map((value) => JSON.stringify(value)).join(", ")}])`;
    case "array":
      return `z.array(${zodExpression(type.of)})`;
    case "union":
      return `z.union([${type.of.map(zodExpression).join(", ")}])`;
    case "object": {
      const entries = Object.entries(type.fields);
      if (entries.length === 0) return "z.object({})";
      const fields = entries
        .map(([name, field]) => `${name}: ${zodExpression(field.type)}${field.optional ? ".optional()" : ""}`)
        .join(", ");
      return `z.object({ ${fields} })`;
    }
  }
}

function portsObject(ports: Record<string, Port>): string {
  const entries = Object.entries(ports);
  if (entries.length === 0) return "z.object({})";
  const lines = entries.map(([name, port]) => `  ${name}: ${zodExpression(port.type)},`);
  return `z.object({\n${lines.join("\n")}\n})`;
}

function relativeRootPrefix(blockPath: string): string {
  return "../".repeat(blockPath.split("/").length);
}

/**
 * How a capability port is written where a block declares it: `FileSystem`,
 * or `Store<Account>` for one that is a way into something with a shape.
 *
 * A bound port with nothing to fill in falls back to `unknown`, which is
 * honest — `check` reports the unbound port separately, and a contract that
 * would not compile helps nobody find it.
 */
function capabilityType(capability: string, row: PortType | undefined): string {
  const parameter = CAPABILITIES[capability]?.parameter;
  if (!parameter) return capability;
  return `${capability}<${row ? describeType(row) : "unknown"}>`;
}

function operationSignature(operation: CapabilityOperation): string {
  const parameters = operation.parameters.map((p) => `${p.name}: ${describeType(p.type)}`).join(", ");
  const returns = operation.returns ? describeType(operation.returns) : "void";
  return `  ${operation.name}(${parameters}): ${operation.async ? `Promise<${returns}>` : returns};`;
}

const GENERATED = "// Generated by Fragmentor from block.json. Do not edit: change the diagram instead.";

/** Words TypeScript will not take as a variable, and names the generated code already uses. */
const RESERVED = new Set([
  "break", "case", "catch", "class", "const", "continue", "debugger", "default", "delete", "do", "else", "enum",
  "export", "extends", "false", "finally", "for", "function", "if", "import", "in", "instanceof", "new", "null",
  "return", "super", "switch", "this", "throw", "true", "try", "typeof", "var", "void", "while", "with", "yield",
  "let", "static", "implements", "interface", "package", "private", "protected", "public", "await", "async",
  "arguments", "eval", "undefined", "NaN", "Infinity",
  "input", "caps", "result", "Promise",
]);

const naming: Naming = {
  variable: (port) => port,
  qualified: (first, second) => camelCase(first) + second.charAt(0).toUpperCase() + second.slice(1),
  functionName: camelCase,
  results: (blockId, each) => (each ? `${camelCase(blockId)}Results` : null),
  reserved: RESERVED,
};

/** `{ order }` when the names agree, `{ totals: total }` when they do not. Destructuring reads the same way. */
function object(bindings: Binding[]): string {
  if (bindings.length === 0) return "{}";
  return `{ ${bindings.map(({ port, variable }) => (port === variable ? port : `${port}: ${variable}`)).join(", ")} }`;
}

function compositeSource(block: Block): string {
  const plan = planComposite(block, naming);
  const [input, output, caps] = (["Input", "Output", "Caps"] as const).map((role) => `${pascalCase(block.id)}${role}`);

  const paragraphs: string[] = [];
  if (plan.inputs.length > 0) paragraphs.push(`  const ${object(plan.inputs)} = input;`);

  for (const step of plan.steps) {
    const call = `${step.callee}(${object(step.args)}, caps)`;
    if (!step.each) {
      paragraphs.push(step.outputs.length > 0 ? `  const ${object(step.outputs)} = await ${call};` : `  await ${call};`);
      continue;
    }

    const start = step.result ? `  const ${step.result} = await Promise.all(` : "  await Promise.all(";
    const map = `${step.each.over}.map((${step.each.item}) => ${call})`;
    const lines = [`${start}${map});`.length <= 100 ? `${start}${map});` : `${start}\n    ${map},\n  );`];
    for (const produced of step.outputs) {
      lines.push(`  const ${produced.variable} = ${step.result}.map((result) => result.${produced.port});`);
    }
    paragraphs.push(lines.join("\n"));
  }

  paragraphs.push(`  return ${object(plan.returns)};`);

  return [
    GENERATED,
    `import type { ${input}, ${output}, ${caps} } from "./contract.js";`,
    ...plan.callees.map(
      ({ child, name, local }) => `import { ${name === local ? name : `${name} as ${local}`} } from "./${child}/impl.js";`,
    ),
    ``,
    `/** ${block.responsibility} */`,
    `export async function ${camelCase(block.id)}(input: ${input}, caps: ${caps}): Promise<${output}> {`,
    paragraphs.join("\n\n"),
    `}`,
    ``,
  ].join("\n");
}

export const typescriptPack: LanguagePack = {
  id: "typescript",
  displayName: "TypeScript",
  contractFile: "contract.ts",
  implFile: "impl.ts",
  capabilitiesFile: "capabilities.ts",

  functionName: (blockId) => camelCase(blockId),
  typeName: (blockId, role) => `${pascalCase(blockId)}${role}`,
  typeExpression: (type) => describeType(type),

  contractSource({ block, blockPath, bound }: ContractRequest): string {
    const fn = camelCase(block.id);
    const capabilities = Object.entries(block.capabilities);
    const capabilityTypes = [...new Set(capabilities.map(([, cap]) => cap.capability))].sort();

    const parts: string[] = [
      `// Generated by Fragmentor from block.json. Do not edit.`,
      `// ${block.name}: ${block.responsibility}`,
      ``,
      `import { z } from "zod";`,
    ];

    if (capabilityTypes.length > 0) {
      parts.push(`import type { ${capabilityTypes.join(", ")} } from "${relativeRootPrefix(blockPath)}capabilities.js";`);
    }

    parts.push(
      ``,
      `export const ${fn}Input = ${portsObject(block.inputs)};`,
      ``,
      `export type ${this.typeName(block.id, "Input")} = z.infer<typeof ${fn}Input>;`,
      ``,
      `export const ${fn}Output = ${portsObject(block.outputs)};`,
      ``,
      `export type ${this.typeName(block.id, "Output")} = z.infer<typeof ${fn}Output>;`,
      ``,
    );

    const capsName = this.typeName(block.id, "Caps");
    if (capabilities.length === 0) {
      // An empty interface, not `Record<string, never>`: a block that needs no
      // effects still has to accept whatever its parent passes down, and
      // `never` members would reject exactly that.
      parts.push(`/** ${block.name} needs no effects supplied from outside. */`);
      parts.push(`export interface ${capsName} {}`);
    } else {
      const fields = capabilities.map(([name, cap]) => {
        const comment = cap.description ? `  /** ${cap.description} */\n` : "";
        return `${comment}  ${name}: ${capabilityType(cap.capability, bound?.[name])};`;
      });
      parts.push(`export interface ${capsName} {\n${fields.join("\n")}\n}`);
    }

    return `${parts.join("\n")}\n`;
  },

  implScaffold(block: Block): string {
    const input = this.typeName(block.id, "Input");
    const output = this.typeName(block.id, "Output");
    const caps = this.typeName(block.id, "Caps");
    const fn = camelCase(block.id);

    return [
      `import type { ${input}, ${output}, ${caps} } from "./contract.js";`,
      ``,
      `/** ${block.responsibility} */`,
      `export async function ${fn}(input: ${input}, caps: ${caps}): Promise<${output}> {`,
      `  throw new Error("${block.name} ${UNIMPLEMENTED}.");`,
      `}`,
      ``,
    ].join("\n");
  },

  compositeSource,

  capabilitiesSource(): string {
    const declarations = Object.values(CAPABILITIES).map((capability) => {
      const operations = capability.operations
        .map((operation) => `  /** ${operation.description} */\n${operationSignature(operation)}`)
        .join("\n");
      const head = capability.parameter ? `${capability.name}<${capability.parameter}>` : capability.name;
      return `/** ${capability.description} */\nexport interface ${head} {\n${operations}\n}`;
    });

    return `// Generated by Fragmentor. Do not edit.\n\n${declarations.join("\n\n")}\n`;
  },

  canRun: true,
  canCheck: true,
  isUnimplemented: (source) => source.includes(UNIMPLEMENTED),
};

registerPack(typescriptPack);
