import { access, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import type { Mode } from "../model/block.js";
import { CAPABILITIES, isKnownCapability } from "../model/capabilities.js";
import { validateComposite } from "../model/validate.js";
import { getPack, isKnownLanguage } from "../lang/index.js";
import { blocksRoot, holdsPlan, manifestPath, systemOf, writeManifest } from "../project/project.js";
import type { Manifest, Project, Start } from "../project/project.js";
import { AGENTS_FILE, AGENTS_SCAFFOLD, CLAUDE_FILE, CLAUDE_SCAFFOLD, GUIDE_FILE, agentGuide } from "./guide.js";

/**
 * Writes the generated half of a project to disk, one language pack per system.
 *
 * Contracts, composites and the agent's guide are regenerated every time,
 * because they are derived from the diagram and must never drift from it. A
 * leaf's implementation is only ever created when missing: it holds work an
 * agent or a person wrote, and overwriting it would throw that away.
 *
 * A file is only written when its contents change. The application watches
 * the project, and a check that rewrote identical files would redraw the
 * window under the person using it every time the agent ran one.
 *
 * A visual project has no generated code at all. Its code is the person's
 * own, and all Fragmentor keeps current there is the guide.
 *
 * Planned blocks have no code either. A planned block is a drawing of
 * something nobody has written, and a block holding one anywhere beneath it
 * has nothing to generate for the same reason: its code would be a call to a
 * function that does not exist. Whatever Fragmentor generated for such a
 * block before is taken away, so a contract cannot outlive what it described.
 */

export interface EmitResult {
  /** Files created or changed, relative to the project. */
  written: string[];
  /** Implementations that already existed, and were left alone. */
  skipped: string[];
  /** Generated files taken away, because what they described is now planned. */
  removed: string[];
  problems: string[];
}

async function exists(filePath: string): Promise<boolean> {
  try {
    await access(filePath);
    return true;
  } catch {
    return false;
  }
}

async function readIfPresent(filePath: string): Promise<string | null> {
  try {
    return await readFile(filePath, "utf8");
  } catch {
    return null;
  }
}

/**
 * Writes `contents` unless the file already holds them, and says whether it
 * wrote. Line endings are ignored, so a checkout that converted them does not
 * count as a change.
 */
async function writeIfChanged(filePath: string, contents: string): Promise<boolean> {
  if ((await readIfPresent(filePath))?.replace(/\r\n/g, "\n") === contents) return false;
  await writeFile(filePath, contents, "utf8");
  return true;
}

/** Every file Fragmentor generates says so on its first line, which is how one is told apart from someone's work. */
export function isGeneratedSource(source: string): boolean {
  return (source.split("\n", 1)[0] ?? "").includes("Generated by Fragmentor");
}

/**
 * Prepares a folder for a coding agent: the guide, and the two files agents
 * read first, which point at it. Those two are only ever created, never
 * rewritten, because they are where the person keeps instructions of their
 * own. Any that were already there without mentioning the guide are reported,
 * since an agent reading them would never learn that it exists.
 */
export async function writeAgentFiles(
  projectDir: string,
  manifest: Manifest,
): Promise<{ written: string[]; kept: string[]; withoutGuide: string[] }> {
  await mkdir(projectDir, { recursive: true });

  const written = (await writeIfChanged(path.join(projectDir, GUIDE_FILE), agentGuide(manifest))) ? [GUIDE_FILE] : [];
  const kept: string[] = [];
  const withoutGuide: string[] = [];

  for (const [file, contents] of [[AGENTS_FILE, AGENTS_SCAFFOLD], [CLAUDE_FILE, CLAUDE_SCAFFOLD]] as const) {
    const existing = await readIfPresent(path.join(projectDir, file));
    if (existing === null) {
      await writeFile(path.join(projectDir, file), contents, "utf8");
      written.push(file);
    } else {
      kept.push(file);
      if (!existing.includes(GUIDE_FILE)) withoutGuide.push(file);
    }
  }

  return { written, kept, withoutGuide };
}

/** What the person decides when starting a project. */
export interface NewProjectSettings {
  mode: Mode;
  granularity: 1 | 2 | 3 | 4 | 5;
  /** Null when the agent is left to choose. */
  language: string | null;
  /** Whether the folder already holds code the agent has to work with. */
  existingCode: boolean;
  /** Whether the agent draws the architecture as a plan before building it. */
  start: Start;
}

/**
 * Starts a project in a folder, empty or already holding code: fragmentor.json
 * with what the person chose, and the files an agent reads first. The agent
 * fills in the rest.
 */
export async function startProject(
  dir: string,
  settings: NewProjectSettings,
): Promise<{ written: string[]; kept: string[]; withoutGuide: string[] }> {
  if (await exists(manifestPath(dir))) throw new Error(`${dir} is already a Fragmentor project.`);

  const manifest: Manifest = {
    name: path.basename(path.resolve(dir)),
    goal: "",
    mode: settings.mode,
    existingCode: settings.existingCode,
    start: settings.start,
    ...(settings.language ? { language: settings.language } : {}),
    granularity: { level: settings.granularity, maxDepth: 4 },
    systems: [],
  };
  await writeManifest(dir, manifest);

  const files = await writeAgentFiles(dir, manifest);
  return { ...files, written: ["fragmentor.json", ...files.written] };
}

export async function emitProject(project: Project): Promise<EmitResult> {
  const written: string[] = [];
  const skipped: string[] = [];
  const removed: string[] = [];
  const problems: string[] = [];

  const relative = (target: string) => path.relative(project.dir, target).split(path.sep).join("/");
  const write = async (target: string, contents: string) => {
    if (await writeIfChanged(target, contents)) written.push(relative(target));
  };
  /**
   * Takes away a file that is Fragmentor's to take away, and only that.
   * Anything else in a planned block's folder is someone's work, and is
   * reported instead so that they decide what becomes of it.
   */
  const discard = async (target: string, ours: (source: string) => boolean = isGeneratedSource) => {
    const existing = await readIfPresent(target);
    if (existing === null || !ours(existing)) return;
    await rm(target);
    removed.push(relative(target));
  };

  // The guide does not depend on the project being valid, and is most needed
  // when it is not, so it is kept current before anything can be refused.
  await write(path.join(project.dir, GUIDE_FILE), agentGuide(project.manifest));
  if (project.manifest.mode === "visual") return { written, skipped, removed, problems };

  for (const system of project.systems) {
    if (!isKnownLanguage(system.language)) {
      problems.push(`The system "${system.rootBlock}" is written in "${system.language}", which Fragmentor has no language pack for.`);
    }
  }

  for (const node of project.byPath.values()) {
    for (const [name, cap] of Object.entries(node.block.capabilities)) {
      if (!isKnownCapability(cap.capability)) {
        problems.push(
          `"${node.block.name}" asks for a capability "${name}" of an unknown kind "${cap.capability}". Known kinds: ${Object.keys(CAPABILITIES).join(", ")}.`,
        );
      }
    }
  }

  if (problems.length > 0) return { written, skipped, removed, problems };

  // One shared capabilities module per language actually used.
  const languagesUsed = [...new Set(project.systems.map((system) => system.language))];
  for (const language of languagesUsed) {
    const pack = getPack(language);
    await write(path.join(blocksRoot(project.dir), pack.capabilitiesFile), pack.capabilitiesSource());
  }

  for (const node of project.byPath.values()) {
    const system = systemOf(project, node.path);
    if (!system) {
      problems.push(`"${node.path}" does not belong to any system in this project.`);
      continue;
    }
    const pack = getPack(system.language);
    const implFile = path.join(node.dir, pack.implFile);
    const existing = (await readIfPresent(implFile))?.replace(/\r\n/g, "\n") ?? null;

    /**
     * What Fragmentor may rewrite or take away here: code it generated, or
     * the starting point it created that nobody has filled in since.
     *
     * The starting point is matched exactly rather than by the "no
     * implementation yet" marker inside it, because that phrase can appear in
     * real code — in a branch someone has left unfinished, say — and here it
     * decides what gets deleted.
     */
    const ours = (source: string) => isGeneratedSource(source) || source === pack.implScaffold(node.block);

    /** Leaves the block with no code: Fragmentor's own goes, anyone else's is reported. */
    const clearImpl = async (problem: string) => {
      if (existing !== null && !ours(existing)) problems.push(problem);
      else await discard(implFile, ours);
    };

    const handWritten = `"${node.block.name}" has children, so Fragmentor writes its code, but ${relative(implFile)} holds code someone wrote. Move that code into its children, then delete the file so it can be generated.`;

    if (node.block.planned) {
      // Its ports say what is meant to flow rather than what does, so there
      // is no contract to write and nothing to write code against.
      await discard(path.join(node.dir, pack.contractFile));
      await clearImpl(
        `"${node.block.name}" is planned, so it is only a drawing, but ${relative(implFile)} holds code someone wrote. Take "planned" off the block if it is real now, or move that code out of it.`,
      );
      continue;
    }

    await write(path.join(node.dir, pack.contractFile), pack.contractSource({ block: node.block, blockPath: node.path }));

    if (node.block.kind === "composite") {
      // Its code would call a block nobody has written yet, so it waits for
      // the plan beneath it to be built; its own contract is real and stays.
      // Code someone left here is still reported, because while it sits there
      // it would be checked and run as though it were the block.
      if (holdsPlan(node)) {
        await clearImpl(handWritten);
        continue;
      }

      // A diagram with errors in it has no code to become. The errors are
      // already reported with the rest of the diagram's.
      const children = new Map(node.children.map((child) => [child.block.id, child.block]));
      if (validateComposite(node.block, children).some((diagnostic) => diagnostic.severity === "error")) continue;

      if (existing === null || ours(existing)) {
        await write(implFile, pack.compositeSource(node.block));
      } else {
        problems.push(handWritten);
      }
    } else if (existing === null) {
      await write(implFile, pack.implScaffold(node.block));
    } else if (isGeneratedSource(existing)) {
      // It had children until now. The file may already hold the agent's new
      // code beneath the old first line, so it is pointed out, not replaced.
      problems.push(
        `"${node.block.name}" has no children now, so its code is the agent's to write, but ${relative(implFile)} still starts with Fragmentor's "Generated" line. Write the block's own code there, without that line.`,
      );
    } else {
      skipped.push(relative(implFile));
    }
  }

  written.sort();
  skipped.sort();
  removed.sort();
  return { written, skipped, removed, problems };
}
