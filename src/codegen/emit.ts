/**
 * Writes the generated half of a project to disk, one language pack per system.
 *
 * That half is small, and all of it sits inside `blocks/`: each function
 * block's contract and the shared capability interfaces. Beside it are the
 * agent's guide and the slash commands that send the agent to it.
 * Fragmentor writes no code of its own. Every implementation is the agent's,
 * at whatever path its block points at, and nothing of Fragmentor's is ever
 * written into the codebase's own tree. The one time it writes code files is
 * a swap the person asks for (project/history.ts), which puts back what the
 * project's git history holds.
 *
 * What is generated is regenerated every time, because it is derived from the
 * diagram and must never drift from it. A file is only written when its
 * contents change: the application watches the project, and a check that
 * rewrote identical files would redraw the window under the person using it
 * every time the agent ran one.
 *
 * A contract is written for every block one can be written for — a function,
 * not planned, with typed ports, in a language there is a pack for — and taken
 * away as soon as that stops being true, so a contract cannot outlive what it
 * described. Whether the code is then held to it is the code's own business:
 * `code.ts` says how importing it is what binds the two.
 */

export interface EmitResult {
  /** Files created or changed, relative to the project. */
  written: string[];
  /** Generated files taken away, because Fragmentor no longer writes them. */
  removed: string[];
  problems: string[];
}

async function exists(filePath: string): Promise<boolean> {
  try {
    await access(filePath);
    return true;
  } catch {
    return false;
  }
}

async function readIfPresent(filePath: string): Promise<string | null> {
  try {
    return await readFile(filePath, "utf8");
  } catch {
    return null;
  }
}

/**
 * Writes `contents` unless the file already holds them, and says whether it
 * wrote. Line endings are ignored, so a checkout that converted them does not
 * count as a change.
 */
async function writeIfChanged(filePath: string, contents: string): Promise<boolean> {
  if ((await readIfPresent(filePath))?.replace(/\r\n/g, "\n") === contents) return false;
  await writeFile(filePath, contents, "utf8");
  return true;
}

/**
 * What a TypeScript contract and the capabilities beside it were called while
 * they were `.ts` files holding zod schemas, before they became declarations.
 * One found is taken away, so a project moves over at its next check: left
 * there, it would import zod and be compiled into the codebase's own build.
 */
const FORMER_CONTRACT = "contract.ts";
const FORMER_CAPABILITIES = "capabilities.ts";

/** Every file Fragmentor generates says so on its first line, which is how one is told apart from someone's work. */
export function isGeneratedSource(source: string): boolean {
  return (source.split("\n", 1)[0] ?? "").includes("Generated by Fragmentor");
}

/**
 * Brings the guide in a project up to date, and says whether that took a
 * write. Anything that relies on the agent knowing what the guide says now,
 * such as what to do with the notes the person leaves, calls this first.
 */
export async function writeGuide(projectDir: string, manifest: Manifest): Promise<boolean> {
  return writeIfChanged(path.join(projectDir, GUIDE_FILE), agentGuide(manifest));
}

/**
 * Brings the slash commands a project offers in Claude Code up to date, one
 * skill for each of the phrases the person sets the agent going with, and
 * says which it wrote. Only a skill Fragmentor wrote is ever changed, and
 * nothing else in the folder is touched, since the person keeps skills of
 * their own there, some perhaps made by copying one of these.
 */
export async function writeCommandSkills(projectDir: string): Promise<string[]> {
  const written: string[] = [];
  for (const command of COMMANDS) {
    const file = path.join(projectDir, ...SKILLS_DIR.split("/"), skillName(command), "SKILL.md");
    const existing = await readIfPresent(file);
    if (existing !== null && !isGeneratedSkill(existing)) continue;
    await mkdir(path.dirname(file), { recursive: true });
    if (await writeIfChanged(file, commandSkill(command))) written.push(`${SKILLS_DIR}/${skillName(command)}/SKILL.md`);
  }
  return written;
}

/**
 * Prepares a folder for a coding agent: the guide, and the two files agents
 * read first, which point at it. Those two are only ever created, never
 * rewritten, because they are where the person keeps instructions of their
 * own. Any that were already there without mentioning the guide are reported,
 * since an agent reading them would never learn that it exists. The slash
 * commands come too, so a new project offers them from the start.
 */
export async function writeAgentFiles(
  projectDir: string,
  manifest: Manifest,
): Promise<{ written: string[]; kept: string[]; withoutGuide: (typeof AGENTS_FILE | typeof CLAUDE_FILE)[] }> {
  await mkdir(projectDir, { recursive: true });

  const written = (await writeGuide(projectDir, manifest)) ? [GUIDE_FILE] : [];
  const kept: string[] = [];
  const withoutGuide: (typeof AGENTS_FILE | typeof CLAUDE_FILE)[] = [];

  for (const [file, contents] of [[AGENTS_FILE, AGENTS_SCAFFOLD], [CLAUDE_FILE, CLAUDE_SCAFFOLD]] as const) {
    const existing = await readIfPresent(path.join(projectDir, file));
    if (existing === null) {
      await writeFile(path.join(projectDir, file), contents, "utf8");
      written.push(file);
    } else {
      kept.push(file);
      if (!existing.includes(GUIDE_FILE)) withoutGuide.push(file);
    }
  }
  written.push(...(await writeCommandSkills(projectDir)));

  return { written, kept, withoutGuide };
}

/** The one line that points an agent's own instructions file at the guide. */
export function guideLine(file: string): string {
  return file === CLAUDE_FILE ? `@${GUIDE_FILE}` : `Read ${GUIDE_FILE} before changing anything.`;
}

/**
 * Adds that line to the end of an AGENTS.md or CLAUDE.md the person already
 * had, and says whether it did. The file is theirs, so this is only done when
 * they press the button that asks for it, and never twice: a file that already
 * mentions the guide is left exactly as it is.
 */
export async function pointAtGuide(projectDir: string, file: typeof AGENTS_FILE | typeof CLAUDE_FILE): Promise<boolean> {
  const at = path.join(projectDir, file);
  const existing = await readFile(at, "utf8");
  if (existing.includes(GUIDE_FILE)) return false;
  // A paragraph of its own, so it is not run into whatever the file ended with.
  const gap = existing === "" || /\n\r?\n$/.test(existing) ? "" : existing.endsWith("\n") ? "\n" : "\n\n";
  await appendFile(at, `${gap}${guideLine(file)}\n`, "utf8");
  return true;
}

/** Whether a folder holds anything of its own. Hidden entries such as `.git` do not count. */
export async function holdsFiles(dir: string): Promise<boolean> {
  return (await readdir(dir)).some((name) => !name.startsWith("."));
}

/** What the person decides when starting a project. */
export interface NewProjectSettings {
  granularity: 1 | 2 | 3 | 4 | 5;
  /** Null when the agent is left to choose. */
  language: string | null;
  /** Whether the folder already holds code the agent has to work with. */
  existingCode: boolean;
  /** Whether the agent draws the architecture as a plan before building it. */
  start: Start;
}

/** The settings as the window sent them. The window is not trusted to send sensible ones. */
export function settingsFrom(raw: unknown): NewProjectSettings {
  const value = (raw ?? {}) as Partial<Record<keyof NewProjectSettings, unknown>>;
  if (typeof value.granularity !== "number" || ![1, 2, 3, 4, 5].includes(value.granularity)) {
    throw new Error("Choose how finely to divide the work, from 1 to 5.");
  }

  if (typeof value.existingCode !== "boolean") {
    throw new Error("Choose whether you are starting from scratch or working with code you already have.");
  }
  if (value.start !== "plan" && value.start !== "build") {
    throw new Error("Choose whether to plan the architecture first or build it straight away.");
  }
  if (value.existingCode && value.start === "plan") {
    throw new Error("Code that already exists is described or rebuilt, not planned. Start from scratch to plan an architecture.");
  }

  const language = typeof value.language === "string" && value.language.trim() ? value.language.trim().slice(0, 40) : null;

  return {
    granularity: value.granularity as NewProjectSettings["granularity"],
    language,
    existingCode: value.existingCode,
    start: value.start,
  };
}

/**
 * Starts a project in a folder, empty or already holding code: fragmentor.json
 * with what the person chose, and the files an agent reads first. The agent
 * fills in the rest.
 *
 * A block's earlier versions are the commits of the repository holding the
 * project, so a folder that is in none gets one here, and `history` says what
 * was found or done.
 */
export async function startProject(
  dir: string,
  settings: NewProjectSettings,
): Promise<{ written: string[]; kept: string[]; withoutGuide: (typeof AGENTS_FILE | typeof CLAUDE_FILE)[]; history: string }> {
  if (await exists(manifestPath(dir))) throw new Error(`${dir} is already a Fragmentor project.`);

  const manifest: Manifest = {
    name: path.basename(path.resolve(dir)),
    goal: "",
    existingCode: settings.existingCode,
    start: settings.start,
    ...(settings.language ? { language: normaliseLanguage(settings.language) } : {}),
    granularity: { level: settings.granularity, maxDepth: 4 },
    systems: [],
  };
  await writeManifest(dir, manifest);

  const files = await writeAgentFiles(dir, manifest);
  const history = await startHistory(dir);
  return { ...files, written: ["fragmentor.json", ...files.written, ...history.written], history: history.note };
}

/**
 * The shape behind each of a block's bound capability ports, so a `Store` is
 * written in terms of what it actually holds rather than of `unknown`.
 */
function boundShapes(project: Project, node: LoadedBlock): Record<string, PortType> {
  return Object.fromEntries(
    boundStores(project, node)
      .filter((store) => store.shape !== null)
      .map((store) => [store.port, store.shape!]),
  );
}

export async function emitProject(project: Project, known?: Map<string, BlockCode>): Promise<EmitResult> {
  const written: string[] = [];
  const removed: string[] = [];
  const problems: string[] = [];

  const relative = (target: string) => path.relative(project.dir, target).split(path.sep).join("/");
  const write = async (target: string, contents: string) => {
    if (await writeIfChanged(target, contents)) written.push(relative(target));
  };
  /** Takes away a file of Fragmentor's, and only ever one of Fragmentor's. */
  const discard = async (target: string) => {
    const existing = await readIfPresent(target);
    if (existing === null || !isGeneratedSource(existing)) return;
    await rm(target);
    removed.push(relative(target));
  };
  /**
   * A `.ts` file of someone's own, kept where a generated one would be taken
   * away. TypeScript finds it before the `.d.ts` beside it, so code importing
   * the contract would be checked against the wrong types.
   */
  const shadowing = async (target: string) => {
    if ((await readIfPresent(target)) === null) return;
    problems.push(
      `${relative(target)} was not written by Fragmentor, and TypeScript reads it in place of the ${path.basename(target, ".ts")}.d.ts that Fragmentor writes beside it. Move or rename it.`,
    );
  };

  // The guide does not depend on the project being valid, and is most needed
  // when it is not, so it is kept current before anything can be refused, and
  // so are the slash commands that send the agent to it.
  await write(path.join(project.dir, GUIDE_FILE), agentGuide(project.manifest));
  written.push(...(await writeCommandSkills(project.dir)));

  for (const node of project.byPath.values()) {
    for (const [name, cap] of Object.entries(node.block.capabilities)) {
      if (!isKnownCapability(cap.capability)) {
        problems.push(
          `"${node.block.name}" asks for a capability "${name}" of an unknown kind "${cap.capability}". Known kinds: ${Object.keys(CAPABILITIES).join(", ")}.`,
        );
      }
    }
  }

  if (problems.length > 0) return { written, removed, problems };

  const code = known ?? (await readAllCode(project));
  const written_for = new Set<string>();

  for (const node of project.byPath.values()) {
    await discard(path.join(node.dir, FORMER_CONTRACT));
    const found = code.get(node.path);
    const pack = found?.contract === null || found === undefined ? null : packFor(project, node.path);

    if (pack === null || found?.contract === undefined || found.contract === null) {
      // Not a function, planned, written in words, or in a language there is no
      // pack for. Anything written for it before — in any language, since a
      // system's may have changed — describes something that is no longer there.
      for (const each of knownLanguages()) await discard(path.join(node.dir, getPack(each.id).contractFile));
      continue;
    }

    await write(
      path.join(project.dir, ...found.contract.split("/")),
      pack.contractSource({ block: node.block, blockPath: node.path, bound: boundShapes(project, node) }),
    );
    written_for.add(pack.id);
    if (pack.id === "typescript") await shadowing(path.join(node.dir, FORMER_CONTRACT));
    // A contract in the language this system used to be written in describes
    // the same block in words that no longer apply to it.
    for (const each of knownLanguages()) {
      if (each.id !== pack.id) await discard(path.join(node.dir, getPack(each.id).contractFile));
    }
  }

  // The shared capabilities module, for each language something was written in,
  // and no other: one nobody can import is a file nobody reads.
  await discard(path.join(blocksRoot(project.dir), FORMER_CAPABILITIES));
  for (const each of knownLanguages()) {
    const pack = getPack(each.id);
    const file = path.join(blocksRoot(project.dir), pack.capabilitiesFile);
    if (written_for.has(pack.id)) await write(file, pack.capabilitiesSource());
    else await discard(file);
  }
  if (written_for.has("typescript")) await shadowing(path.join(blocksRoot(project.dir), FORMER_CAPABILITIES));

  written.sort();
  removed.sort();
  return { written, removed, problems };
}
