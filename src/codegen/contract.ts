import type { Block } from "../model/block.js";
import { functionNameOf, typeStemOf } from "../model/block.js";
import { describeType } from "../model/types.js";
import type { PortType } from "../model/types.js";

/**
 * Generates the contract half of a block: the runtime schemas for its ports,
 * the TypeScript types derived from them, and the shape of its capabilities.
 *
 * This part is mechanical, so it is generated rather than written by the model.
 * What the block actually *does* is not generated here — a leaf's body is
 * written by the model, and a composite's glue is too, then checked against
 * the diagram. Only the contract is derived, because a contract that
 * disagreed with block.json would make every other check meaningless.
 */

/** A zod expression that validates values of this port type. */
export function zodExpression(type: PortType): string {
  switch (type.kind) {
    case "string":
      return "z.string()";
    case "number":
      return "z.number()";
    case "boolean":
      return "z.boolean()";
    case "null":
      return "z.null()";
    case "unknown":
      return "z.unknown()";
    case "literal":
      return `z.literal(${JSON.stringify(type.value)})`;
    case "enum":
      return `z.enum([${type.values.map((v) => JSON.stringify(v)).join(", ")}])`;
    case "array":
      return `z.array(${zodExpression(type.of)})`;
    case "union":
      return `z.union([${type.of.map(zodExpression).join(", ")}])`;
    case "object": {
      const entries = Object.entries(type.fields);
      if (entries.length === 0) return "z.object({})";
      const fields = entries
        .map(([name, field]) => `${name}: ${zodExpression(field.type)}${field.optional ? ".optional()" : ""}`)
        .join(", ");
      return `z.object({ ${fields} })`;
    }
  }
}

/** The TypeScript type for a port. The stored syntax is already valid TypeScript. */
export function typeExpression(type: PortType): string {
  return describeType(type);
}

function portsObject(ports: Record<string, { type: PortType }>): string {
  const entries = Object.entries(ports);
  if (entries.length === 0) return "z.object({})";
  const lines = entries.map(([name, port]) => `  ${name}: ${zodExpression(port.type)},`);
  return `z.object({\n${lines.join("\n")}\n})`;
}

/** How many `../` steps separate a block from the root of the blocks tree. */
export function relativeRootPrefix(blockPath: string): string {
  const depth = blockPath.split("/").length;
  return "../".repeat(depth);
}

export interface ContractSourceOptions {
  block: Block;
  /** Slash-joined path from the blocks root, used to locate shared modules. */
  blockPath: string;
}

export function generateContractSource({ block, blockPath }: ContractSourceOptions): string {
  const stem = typeStemOf(block.id);
  const fn = functionNameOf(block.id);
  const capabilities = Object.entries(block.capabilities);
  const capabilityTypes = [...new Set(capabilities.map(([, cap]) => cap.capability))].sort();

  const parts: string[] = [
    `// Generated by Fragmentor from block.json. Do not edit.`,
    `// ${block.name}: ${block.responsibility}`,
    ``,
    `import { z } from "zod";`,
  ];

  if (capabilityTypes.length > 0) {
    parts.push(
      `import type { ${capabilityTypes.join(", ")} } from "${relativeRootPrefix(blockPath)}capabilities.js";`,
    );
  }

  parts.push(
    ``,
    `export const ${fn}Input = ${portsObject(block.inputs)};`,
    ``,
    `export type ${stem}Input = z.infer<typeof ${fn}Input>;`,
    ``,
    `export const ${fn}Output = ${portsObject(block.outputs)};`,
    ``,
    `export type ${stem}Output = z.infer<typeof ${fn}Output>;`,
    ``,
  );

  if (capabilities.length === 0) {
    parts.push(`/** ${block.name} needs no effects supplied from outside. */`);
    parts.push(`export type ${stem}Caps = Record<string, never>;`);
  } else {
    const fields = capabilities.map(([name, cap]) => {
      const comment = cap.description ? `  /** ${cap.description} */\n` : "";
      return `${comment}  ${name}: ${cap.capability};`;
    });
    parts.push(`export interface ${stem}Caps {\n${fields.join("\n")}\n}`);
  }

  return `${parts.join("\n")}\n`;
}

/**
 * The signature a block's implementation must have. A leaf's body is written
 * by the model; this is the frame it writes inside, so the frame can never
 * disagree with the diagram.
 */
export function generateImplSignature(block: Block): string {
  const stem = typeStemOf(block.id);
  const fn = functionNameOf(block.id);
  return `export async function ${fn}(input: ${stem}Input, caps: ${stem}Caps): Promise<${stem}Output>`;
}

export function generateImplScaffold(block: Block): string {
  const stem = typeStemOf(block.id);
  return [
    `import type { ${stem}Input, ${stem}Output, ${stem}Caps } from "./contract.js";`,
    ``,
    `/** ${block.responsibility} */`,
    `${generateImplSignature(block)} {`,
    `  throw new Error("${block.name} has no implementation yet.");`,
    `}`,
    ``,
  ].join("\n");
}
