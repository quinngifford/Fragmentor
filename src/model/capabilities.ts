/**
 * The effects a block can ask for.
 *
 * A capability is an interface supplied from outside the block, which is what
 * lets any block run in isolation with a substitute in place. The catalogue is
 * fixed for now: a user-defined capability is a real feature, but nothing yet
 * needs one, and a fixed set keeps generated code honest about what a block
 * can reach.
 */
export interface CapabilityDefinition {
  name: string;
  description: string;
  /** The TypeScript declaration emitted into a generated project. */
  declaration: string;
}

export const CAPABILITIES: Record<string, CapabilityDefinition> = {
  FileSystem: {
    name: "FileSystem",
    description: "Reads and writes files.",
    declaration: `export interface FileSystem {
  readFile(path: string): Promise<string>;
  writeFile(path: string, contents: string): Promise<void>;
}`,
  },
  Http: {
    name: "Http",
    description: "Fetches over the network.",
    declaration: `export interface Http {
  get(url: string): Promise<string>;
}`,
  },
  Clock: {
    name: "Clock",
    description: "Reads the current time.",
    declaration: `export interface Clock {
  now(): Date;
}`,
  },
  Random: {
    name: "Random",
    description: "Produces random numbers.",
    declaration: `export interface Random {
  next(): number;
}`,
  },
  Logger: {
    name: "Logger",
    description: "Records what happened.",
    declaration: `export interface Logger {
  log(message: string): void;
}`,
  },
};

export function isKnownCapability(name: string): boolean {
  return Object.hasOwn(CAPABILITIES, name);
}

/** The shared module a generated project imports its capability types from. */
export function capabilitiesModuleSource(): string {
  const declarations = Object.values(CAPABILITIES).map((c) => `/** ${c.description} */\n${c.declaration}`);
  return `// Generated by Fragmentor. Do not edit.\n\n${declarations.join("\n\n")}\n`;
}
